package dsa;

public class WhileAndForLoop {
	public static void main(String[] args) {
		
		int i = 1;
		
		while(i <= 3) {
			System.out.println("i = " + i);
			i++;
		}
		System.out.println("Done.");
		
		
		//for loop
		for(int j=1; j<=5;j++) {
			System.out.println(" j is  : " + j);
		}
		
	}
}
